package com.bespectacledcyborg.remoteexplorer.data.crypto

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * AES-GCM with a key the app cannot export, held by the Android Keystore.
 *
 * The key is generated once on first use and never leaves the Keystore — this class only ever
 * holds a handle to it, so a database copied off the device cannot be decrypted elsewhere even
 * with the APK in hand.
 *
 * GCM is chosen over CBC because it authenticates: a tampered row fails to decrypt loudly
 * rather than yielding a plausible wrong password and an SMB login failure nobody can explain.
 */
class KeystoreCredentialCipher : CredentialCipher {

    private val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }

    private fun key(): SecretKey {
        (keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                // NOT setUserAuthenticationRequired(true): thumbnails load in a background
                // worker, so a key that needed a screen unlock would fail there rather than
                // prompting, and the share would half-load with no way to tell why.
                .build()
        )
        return generator.generateKey()
    }

    override fun encrypt(secret: SecretText): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        val payload = cipher.doFinal(secret.value.toByteArray(Charsets.UTF_8))
        // The IV is generated by the Keystore, never reused, and is not secret — it travels
        // with the ciphertext so the single TEXT column stays self-contained.
        return CredentialCipher.IV_PREFIX +
            Base64.encodeToString(cipher.iv, Base64.NO_WRAP) +
            ":" +
            Base64.encodeToString(payload, Base64.NO_WRAP)
    }

    override fun decrypt(stored: String): SecretText {
        if (!isEncrypted(stored)) return SecretText(stored)

        val (encodedIv, encodedPayload) = stored
            .removePrefix(CredentialCipher.IV_PREFIX)
            .split(":", limit = 2)
            .also { require(it.size == 2) { "encrypted credential is missing its IV" } }

        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(
            Cipher.DECRYPT_MODE,
            key(),
            GCMParameterSpec(TAG_LENGTH_BITS, Base64.decode(encodedIv, Base64.NO_WRAP)),
        )
        val plaintext = cipher.doFinal(Base64.decode(encodedPayload, Base64.NO_WRAP))
        return SecretText(String(plaintext, Charsets.UTF_8))
    }

    private companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "remote_explorer_credentials"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val TAG_LENGTH_BITS = 128
    }
}
